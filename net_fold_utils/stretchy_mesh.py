"""Loader + solver for STRETCHY meshes: a closed polyhedron-like net whose
faces are combinatorially valid (every edge shared by exactly two faces)
but that cannot necessarily be realized with perfectly RIGID, FLAT faces
-- e.g. two faces glued together along more than one shared edge, which
forces them into the same plane if both stay flat and rigid (three or
more shared, non-collinear points determine a single plane, so any two
flat polygons sharing that many points must lie in it -- there's no
dihedral fold left to make them distinct faces of a solid). The
net_fold_utils.polyhedron_spec / combinatorics.EdgeMap pipeline used by
polygon_fold_app.py and polyhedral_net_app.py can't even represent this:
EdgeMap's face-adjacency graph is a plain networkx.Graph, so two faces
sharing more than one edge collapses to a single graph edge and raises
"duplicate edge in the edge list" (see tests/test_stretchy_mesh.py for a
worked example, and stretchy_polyhedron_init.py for the app that handles
these).

Rather than the rigid pipeline's hinge-tree-plus-fold-angles model (which
assumes every face stays flat), a stretchy mesh is specified directly as
VERTEX loops -- the standard "indexed face set" representation (like an
.obj file): shared vertices ARE the adjacency, so faces sharing multiple
edges need no special-casing, and there's no "flat 2D net" or "fold
angle" concept to derive at all. JSON shape:

    {
      "name": "...",
      "faces": [
        [0, 1, 2, 3, 4],
        [3, 2, 1, 0, 5],
        [0, 4, 3, 5]
      ]
    }

WINDING CONVENTION: each face is a loop of vertex ids (ints, 0..N-1,
referenced -- not separately declared; N is inferred as 1 + the largest
id used) listed COUNTERCLOCKWISE as seen from OUTSIDE the finished
solid -- the same convention as net_layout.py / polygon_geom.py (and,
transitively, hull_to_spec.py's own CCW-outward face loops, which is
where tools/generate_stretchy_platonic_nets.py's faces come from
directly). Concretely, this means: for any edge (v, w) shared by two
faces, one face's loop contains it as v -> w and the other's contains
it as w -> v -- never the same direction twice. load_stretchy_mesh
checks exactly that (every directed edge matched by exactly one reverse
partner in some other face) and raises a clear error naming the
offending edge(s) if it's violated, so a face listed backwards relative
to its neighbors is caught immediately, before ever reaching the solver.

That check alone can't catch every possible mistake, though: flipping
EVERY face at once (a full mirror image) is just as valid a loop
structure as the original -- reversing one face by itself is what
breaks it, and that's what gets caught. A subtler problem can still
reach the solver even so: solve_wireframe's plain edge-length fit has
many solutions for a well-connected mesh, and some of them fold one
face inside-out relative to the rest even though the abstract loops are
perfectly consistent -- the exact same "collapsed branch" issue
fold_solver._is_embeddable guards against for the rigid pipeline (see
its docstring). solve_wireframe checks for this too (see
_is_orientation_consistent) and specifically searches for a consistent
embedding rather than accepting the first thing that satisfies the edge
lengths; if it truly can't find one after many attempts, it raises
ValueError with a suggestion to double check face winding -- and
build_stretchy_cache.py surfaces that error per-net rather than caching
a bad (or, as observed for two_pentagons_and_a_square.json before this
check existed, suspiciously flat and uninflated) result.

solve_wireframe() then finds SOME 3D position for every vertex that
keeps every edge close to unit length, without requiring individual
faces to stay flat -- letting edges stretch a little and faces bend is
exactly what makes an otherwise-rigid-impossible net (like
stretchy_nets/two_pentagons_and_a_square.json) realizable at all. It
works equally well on an ordinary closed solid (see
stretchy_nets/{tetrahedron,cube,octahedron,icosahedron,dodecahedron}.json,
generated by tools/generate_stretchy_platonic_nets.py from the very same
coordinates the RIGID nets/*.json specs come from) -- those settle with
only a few percent stretch, puffed out into a rounded, convex,
plushie-like shape rather than a collapsed/tangled one (see
solve_wireframe's docstring for how -- an outward "inflation" pressure,
literally the same idea as stuffing/blowing up a plush toy or balloon
until the fabric's own tension stops it).
"""
import json

import numpy as np
from scipy.optimize import least_squares

EDGE_LENGTH = 1.0

# Bump whenever solve_wireframe's algorithm changes enough to produce a
# meaningfully different result for the same mesh (e.g. adding the
# inflation stage) -- net_fold_utils.stretchy_cache folds this into its
# cache key, so a solver change invalidates every existing cache entry
# even though the source .json files themselves haven't changed at all.
# Without this, stretchy_cache/ would keep silently serving results from
# a since-replaced algorithm (e.g. pre-inflation, tangled/skewed ones)
# forever, since its checksum only ever tracked the *source* .json.
ALGORITHM_VERSION = 5


def _face_edges(face):
    """The directed edges (v, w) of one CCW face loop."""
    k = len(face)
    return [(face[i], face[(i + 1) % k]) for i in range(k)]


def load_stretchy_mesh(path):
    """Parse the vertex-loop JSON format above. Returns (faces, name),
    faces a list of vertex-id lists. Raises ValueError if any directed
    edge isn't matched by exactly one reverse-direction partner (i.e. the
    faces don't combinatorially close into a 2-manifold)."""
    with open(path) as f:
        spec = json.load(f)

    faces = spec.get("faces") or []
    if not faces:
        raise ValueError(f"{path}: no faces declared")
    for face in faces:
        if len(face) < 3:
            raise ValueError(f"{path}: a face needs at least 3 vertices, got {face}")

    directed = [e for face in faces for e in _face_edges(face)]
    counts = {}
    for e in directed:
        counts[e] = counts.get(e, 0) + 1
    problems = []
    for (v, w), c in counts.items():
        if c > 1:
            problems.append(f"edge {v}->{w} appears {c} times (need exactly once)")
        if (w, v) not in counts:
            problems.append(f"edge {v}->{w} has no reverse partner {w}->{v} in any face")
    if problems:
        raise ValueError(f"{path}: not a closed, consistently-oriented mesh:\n  " +
                          "\n  ".join(problems))

    name = spec.get("name") or path
    return faces, name


def mesh_edges(faces):
    """The mesh's unique undirected edges, as (a, b) with a < b."""
    edges = {tuple(sorted(e)) for face in faces for e in _face_edges(face)}
    return sorted(edges)


def _pair_index_arrays(pairs, idx):
    """A list of (a, b) vertex-id pairs -> two int arrays of their
    positions in the flat point array, for vectorized pairwise-distance
    residuals (np.linalg.norm(pts[a_idx] - pts[b_idx], axis=1)) instead
    of a Python-level loop calling norm() once per pair."""
    if not pairs:
        return np.zeros(0, dtype=int), np.zeros(0, dtype=int)
    a_idx = np.array([idx[a] for a, b in pairs])
    b_idx = np.array([idx[b] for a, b in pairs])
    return a_idx, b_idx


def _volume_indices(faces, idx):
    """Precomputed fan-triangulation index arrays for _mesh_volume: for
    every face, triangulated from its own first vertex into (v0, v_i,
    v_{i+1}) triangles for i = 1..len(face)-2, flattened across all faces
    into three parallel int arrays. Building this ONCE per solve (see
    _edge_setup / solve_wireframe) rather than re-deriving it (a Python
    loop over every face, with a dict lookup per vertex) on every single
    _residual call matters a lot: _residual can run hundreds of times per
    solver step (scipy's finite-difference Jacobian needs roughly
    n_vars+1 evaluations each), so that loop used to execute an enormous
    number of times over the course of any pressure-based relax."""
    v0s, v1s, v2s = [], [], []
    for face in faces:
        face_idx = [idx[v] for v in face]
        for i in range(1, len(face_idx) - 1):
            v0s.append(face_idx[0])
            v1s.append(face_idx[i])
            v2s.append(face_idx[i + 1])
    return (np.array(v0s, dtype=int), np.array(v1s, dtype=int), np.array(v2s, dtype=int))


def _planarity_groups(faces, idx):
    """Precomputed per-face-size index arrays for _face_planarity_residual:
    {n: array of shape (num_faces_with_n_vertices, n)} for every face
    with 4+ vertices (a triangle is always exactly planar and
    contributes nothing, so it's excluded entirely). Grouping by size
    lets _face_planarity_residual batch every same-size face into ONE
    np.linalg.svd call instead of one per face -- built once per solve,
    same rationale as _volume_indices above."""
    groups = {}
    for face in faces:
        n = len(face)
        if n < 4:
            continue
        groups.setdefault(n, []).append([idx[v] for v in face])
    return {n: np.array(rows, dtype=int) for n, rows in groups.items()}


def _face_planarity_residual(pts, planarity_groups):
    """Signed distance of each (4+-vertex) face's points from that face's
    own best-fit plane (via SVD -- the plane through the centroid whose
    normal is the least-variance direction). `planarity_groups` (see
    _planarity_groups) already excludes triangles, which are always
    exactly planar and would contribute nothing; each group (all faces
    sharing one vertex count) is handled with a single batched SVD call
    (`np.linalg.svd` treats the leading dimension of a >2D array as a
    batch of independent matrices) rather than one call per face."""
    if not planarity_groups:
        return np.zeros(0)
    parts = []
    for group_idx in planarity_groups.values():
        face_pts = pts[group_idx]  # (num_faces, n, 3)
        centered = face_pts - face_pts.mean(axis=1, keepdims=True)
        normals = np.linalg.svd(centered, full_matrices=False)[2][:, -1, :]  # (num_faces, 3)
        parts.append(np.einsum('fij,fj->fi', centered, normals).ravel())
    return np.concatenate(parts)


def _mesh_volume(pts, volume_indices):
    """Signed volume enclosed by the mesh, via the divergence theorem:
    fan-triangulate every face from its own first vertex, and sum each
    resulting triangle's signed tetrahedron volume with the origin
    (v0 . (v1 x v2) / 6). Correct (and positive) for any closed,
    consistently outward-CCW-wound, non-self-intersecting mesh -- the
    same orientation convention load_stretchy_mesh already validates.
    Smooth and singularity-free everywhere (unlike, say, 1/distance),
    which is what makes it usable as a least_squares residual term even
    from a poorly-conditioned starting point (see _inflate).

    `volume_indices` is the precomputed (v0_idx, v1_idx, v2_idx) triple
    from _volume_indices -- computed once per solve, not re-derived here,
    so this is a single vectorized sum with no per-face Python loop."""
    v0_idx, v1_idx, v2_idx = volume_indices
    if len(v0_idx) == 0:
        return 0.0
    v0 = pts[v0_idx]
    v1 = pts[v1_idx]
    v2 = pts[v2_idx]
    return float(np.einsum('ij,ij->i', v0, np.cross(v1, v2)).sum() / 6.0)


def _sphere_bound_volume(faces, edge_length):
    """An optimistic (normally unreachable) target volume for _inflate's
    pressure term: the volume of the SPHERE with the same total surface
    area as the mesh's own faces (each assumed a regular polygon of
    `edge_length` sides, even though the actual solved faces may bend a
    little) -- the isoperimetric-maximal shape for that much surface,
    so no achievable inflation ever fully reaches it. Scaled to the
    mesh's own size (not some arbitrary huge constant) so the pressure
    it creates stays reasonable regardless of how big the mesh is: e.g.
    for the regular icosahedron this comes out to ~2.40, within 10% of
    its true volume (~2.18), and for the dodecahedron ~9.30 vs a true
    ~7.66 -- close enough to give real, well-scaled "pressure" without
    wildly overshooting what the mesh could ever actually hold."""
    total_area = sum((k / 4.0) / np.tan(np.pi / k) for k in (len(f) for f in faces))
    total_area *= edge_length ** 2
    r = np.sqrt(total_area / (4 * np.pi))
    return (4 / 3) * np.pi * r ** 3


def _edge_and_planarity_parts(pts, edge_ai, edge_bi, edge_length, planarity_weight, planarity_groups):
    """The two residual pieces shared by _residual (target-based pressure,
    used by _inflate/solve_wireframe) and _relax_residual (target-free
    pressure, used by relax_once): RELATIVE edge-length error for every
    mesh edge (i.e. (actual - rest) / rest, not the raw difference) --
    always first, so callers can slice `result[:len(edge_ai)]` to get
    just the edge-length error -- plus an optional per-face flatness term
    (see _face_planarity_residual). Returns a list of arrays, so the
    caller can append its own pressure term before concatenating.

    `edge_length` may be a scalar (uniform rest length -- the original,
    still-default usage) or a per-edge array aligned with edge_ai/edge_bi
    (a subdivided fabric mesh's edges do NOT all share one rest length,
    see mesh_subdivide.py). Dividing by edge_length rather than using the
    raw difference makes every threshold elsewhere in this module
    (STRETCH_CAP, CONVERGE_TOL) a fraction regardless of scale; for the
    scalar edge_length=1.0 the original callers all use, this is
    numerically identical to the old raw-difference residual."""
    parts = [(np.linalg.norm(pts[edge_ai] - pts[edge_bi], axis=1) - edge_length) / edge_length]
    if planarity_weight:
        parts.append(planarity_weight * _face_planarity_residual(pts, planarity_groups))
    return parts


def _residual(flat, edge_ai, edge_bi, volume_indices, planarity_groups, edge_length,
              inflation_weight=0.0, inflation_target=0.0, planarity_weight=0.0):
    """The full objective for _inflate/solve_wireframe's AUTOMATIC ramp:
    edge-length + planarity (see _edge_and_planarity_parts) plus a
    TARGET-based inflation "pressure" term -- `inflation_weight *
    (inflation_target - volume)`, driving volume toward a fixed,
    precomputed ceiling (_sphere_bound_volume). That ceiling is exactly
    what lets the automatic ramp (INFLATION_WEIGHTS) know it's "done"
    without a human watching -- see _inflate's docstring. relax_once (the
    interactive "Inflate" button) deliberately does NOT use this function
    -- see _relax_residual, which has no target at all, since a human
    dialing in pressure by hand doesn't need or want one.

    `volume_indices`/`planarity_groups` are the precomputed structures
    from _volume_indices/_planarity_groups (built once per solve by the
    caller, e.g. _edge_setup or solve_wireframe) -- NOT `faces`/`idx`
    directly: this function is called extremely often (hundreds of times
    per solver step, since scipy's finite-difference Jacobian needs
    roughly n_vars+1 evaluations each), so re-deriving per-face vertex
    indices via a Python loop + dict lookup on every call was measured as
    a real bottleneck (see git history / the vectorize-mesh-volume task)."""
    pts = flat.reshape(-1, 3)
    parts = _edge_and_planarity_parts(pts, edge_ai, edge_bi, edge_length, planarity_weight, planarity_groups)
    if inflation_weight:
        vol = _mesh_volume(pts, volume_indices)
        parts.insert(1, np.array([inflation_weight * (inflation_target - vol)]))
    return np.concatenate(parts)


def _relax_residual(flat, edge_ai, edge_bi, volume_indices, planarity_groups, edge_length,
                     pressure=0.0, planarity_weight=0.0):
    """relax_once's objective: edge-length + planarity (see
    _edge_and_planarity_parts) plus a TARGET-FREE inflation "pressure"
    term -- `pressure * exp(-volume)`.

    Why no target: _residual's `inflation_weight * (target - volume)`
    term is a two-sided penalty that's zero exactly AT `target` and grows
    whether volume overshoots OR undershoots it -- so once volume gets
    close to that (fixed, precomputed) ceiling, no amount of extra
    pressure can ask for more; it just enforces the SAME ceiling more
    strictly (verified empirically on an earlier version of the default
    cube net: max stretch plateaued around 5.5% from pressure ~100 all
    the way to 300+, because the mesh was already within a fraction of a
    percent of _sphere_bound_volume's target by then). For
    solve_wireframe's automatic ramp that plateau is a FEATURE (see
    _residual's docstring: it's how the ramp knows to stop). For a human
    turning a pressure dial and expecting "more pressure = more
    inflated", it's exactly backwards.

    `pressure * exp(-volume)` has no target and is never satisfied: it
    shrinks toward (but never reaches) zero as volume grows, so there's
    always a gradient rewarding more volume, and the actual equilibrium
    is set entirely by the balance against edge stretch -- a genuinely
    higher pressure asks for genuinely more stretch to rebalance, with no
    ceiling. `exp` (rather than something like `1/volume`) is smooth and
    finite for every volume, including negative/near-zero (a tangled
    starting configuration) -- see _mesh_volume's docstring on why a
    singularity there (like `1/distance`) is specifically something this
    residual family avoids.

    See _residual for what `volume_indices`/`planarity_groups`/
    `edge_length` are (identical here)."""
    pts = flat.reshape(-1, 3)
    parts = _edge_and_planarity_parts(pts, edge_ai, edge_bi, edge_length, planarity_weight, planarity_groups)
    if pressure:
        vol = _mesh_volume(pts, volume_indices)
        parts.insert(1, np.array([pressure * np.exp(-vol)]))
    return np.concatenate(parts)


def _orientation_signs(pts, faces, idx):
    """Sign of each face's own normal relative to "pointing outward from
    the mesh's overall centroid" -- +1 or -1, or 0 for a degenerate face
    (its first 3 points ~collinear, or coincident with the centroid).
    For a genuinely embedded (non-self-intersecting) realization of a
    consistently-oriented mesh (see this module's docstring: CCW as seen
    from outside, matching every neighbor), every face agrees -- all +1
    or all -1, an arbitrary global mirror choice that doesn't matter
    either way. A MIX means this particular solution folds through
    itself somewhere -- some face ended up facing inward relative to
    the rest -- the exact "collapsed branch" phenomenon
    fold_solver._is_embeddable guards against for the rigid pipeline
    (see its module docstring): edge-length equations alone often admit
    a smaller, self-intersecting solution alongside the intended one,
    and nothing about a plain edge-length fit prefers the real one."""
    centroid = pts.mean(axis=0)
    signs = []
    for face in faces:
        face_pts = pts[[idx[v] for v in face]]
        normal = np.cross(face_pts[1] - face_pts[0], face_pts[2] - face_pts[0])
        normal_len = np.linalg.norm(normal)
        outward = face_pts.mean(axis=0) - centroid
        outward_len = np.linalg.norm(outward)
        if normal_len < 1e-9 or outward_len < 1e-9:
            signs.append(0)
        else:
            signs.append(float(np.sign(np.dot(normal / normal_len, outward / outward_len))))
    return signs


def _is_orientation_consistent(pts, faces, idx):
    return len({s for s in _orientation_signs(pts, faces, idx) if s != 0}) <= 1


def _min_pairwise_separation(pts):
    d = np.linalg.norm(pts[:, None, :] - pts[None, :, :], axis=-1)
    np.fill_diagonal(d, np.inf)
    return d.min() if len(pts) > 1 else np.inf


def _overall_3d_extent(pts):
    """The point cloud's smallest principal-axis extent (via SVD) -- near
    zero means the whole mesh has landed flat in a single plane."""
    centered = pts - pts.mean(axis=0)
    return np.linalg.svd(centered, compute_uv=False)[-1]


CONVERGE_TOL = 1e-4  # max |edge length error| to call a plain edge-length solve "converged"
STRETCH_CAP = 0.08  # max |edge length error| _inflate will tolerate before backing off
MIN_3D_EXTENT = 0.1  # fraction of edge_length; below this, call the whole result "flat"

# fraction of edge_length; a final result with two DISTINCT (non-shared)
# vertices closer than this is rejected as degenerate even if
# _is_orientation_consistent didn't happen to flag it -- that check only
# looks at face-normal signs, so it's blind to two unrelated vertices
# landing on (almost) the same point, which _mesh_volume's pressure term
# has no reason to prevent on its own (observed empirically: two
# non-adjacent vertices of a pentagons-and-square candidate collapsing
# to within 1e-8 of each other, in an otherwise orientation-consistent,
# nicely-inflated-looking result).
MIN_SEPARATION_FRACTION = 0.15

# A gradually increasing "pressure" -- each weight is tried as a small
# step up from the last, not from scratch (see _inflate), so the mesh
# inflates smoothly rather than jumping straight to full pressure and
# overshooting.
INFLATION_WEIGHTS = (0.1, 0.2, 0.4, 0.8, 1.5, 3.0)

# How strongly to prefer each face staying close to flat, in the final
# polish pass. Low: _inflate already tends to leave faces close to flat
# on its own (a taut membrane wants to be locally flat wherever its
# edges allow it, same as a real inflated cushion or balloon panel), so
# this only has a little further tidying left to do.
PLANARITY_WEIGHT = 0.1


def _edge_stretch(residual, n_edges):
    return np.max(np.abs(residual[:n_edges])) if n_edges else 0.0


def _inflate(pts0, faces, edge_ai, edge_bi, idx, edge_length, volume_indices, volume_target=None):
    """Gradually "blow up" an already-valid (edges ~= edge_length)
    point cloud into a rounder, more convex shape -- the fix for both
    problems a plain edge-length fit leaves on the table: a mesh with
    enough vertices/edges relative to its face count (e.g. the
    icosahedron: 12 vertices, every one adjacent to 5 of the other 11)
    can settle into a technically valid but badly self-tangled
    embedding, since edge-length fitting alone has no opinion at all
    about the mesh's overall shape or volume; even an untangled one
    (e.g. a plain cube) has no particular reason to come out symmetric
    rather than skewed. Physically this is exactly what stuffing a
    plush toy or inflating a balloon does: a constant outward pressure,
    resisted by the fabric/edges' own tension, settles into a smooth,
    rounded, convex equilibrium -- panels pull flat, corners spread out
    to equidistant, and a self-crossing fold has nowhere to hide once
    everything is under uniform tension pushing out from the middle.

    Implemented as a least_squares term that rewards higher enclosed
    volume (_mesh_volume) against an optimistic, normally-unreachable
    target (_sphere_bound_volume): since it's never satisfied, it keeps
    "pushing" for as long as the edge-length term lets it. Ramping the
    pressure weight up gradually (INFLATION_WEIGHTS) rather than jumping
    straight to full strength, and re-seeding each step from the last
    ACCEPTED one, is what keeps this stable: tried cold (from a random
    point cloud, where distances and volume are tiny and ill-
    conditioned) or all at once at full strength, this same term makes
    least_squares fail to converge at all rather than inflate cleanly
    (verified empirically -- see tests/test_stretchy_mesh.py). A step is
    only kept if it stays within STRETCH_CAP of exact edge length; the
    first step that would overshoot that just stops the ramp early and
    keeps the last good result, rather than fighting a topology that
    genuinely can't hold much pressure (e.g.
    stretchy_nets/two_pentagons_and_a_square.json) into a badly
    stretched mess.

    Deliberately NOT gated on orientation consistency
    (_is_orientation_consistent) at each individual step, even though
    the caller cares about the FINAL result being consistent: tried that
    first, and it made things worse, not better. For the icosahedron
    specifically, the ramp reliably passes through a couple of
    genuinely inconsistent intermediate weights before self-correcting
    at higher pressure (e.g. steps at weight 0.1-0.4 come out
    inconsistent, then 0.8 onward are all fine) -- stopping the ramp at
    the first inconsistent step, as an earlier version of this function
    did, meant it could never reach the weight where it actually
    recovers. Consistency is instead only checked on the ramp's final
    output, by the caller (solve_wireframe): if THAT isn't consistent,
    the fix is to retry from a different stage-1 starting point
    entirely, not to second-guess individual steps of this one.

    Returns (pts, edge_stretch, inflation_weight) -- the last of which
    the caller can reuse as-is for a final planarity pass, so that pass
    doesn't let the pressure relax back down.

    `volume_indices` is the precomputed _volume_indices(faces, idx)
    structure _mesh_volume needs -- built once by the caller rather than
    re-derived on every _residual call (see _residual's docstring).

    `volume_target`, if given, overrides the target volume derived from
    `faces`/`edge_length` -- needed for a subdivided fabric mesh, where
    every face is a small triangle with no consistent side length for
    _sphere_bound_volume's regular-polygon-area formula to use; the
    caller instead derives one target volume from the un-subdivided
    coarse polyhedron (see mesh_subdivide.solve_fabric_mesh)."""
    n_edges = len(edge_ai)
    target = volume_target if volume_target is not None else _sphere_bound_volume(faces, edge_length)
    cur = pts0
    cur_err = _edge_stretch(
        np.linalg.norm(pts0[edge_ai] - pts0[edge_bi], axis=1) - edge_length, n_edges)
    weight_used = 0.0
    for w in INFLATION_WEIGHTS:
        sol = least_squares(_residual, cur.flatten(),
                             args=(edge_ai, edge_bi, volume_indices, None, edge_length, w, target))
        pts = sol.x.reshape(-1, 3)
        err = _edge_stretch(sol.fun, n_edges)
        if err > STRETCH_CAP:
            break
        cur, cur_err, weight_used = pts, err, w
    return cur, cur_err, weight_used


MAX_ORIENTATION_ATTEMPTS = 60  # hard cap on stage-1 restarts spent seeking a usable one
CANDIDATES_PER_ROUND = 8  # how many stage-1 starts to try inflating before giving up a round


def _inflate_from(pts0, faces, edge_ai, edge_bi, idx, edge_length, n_edges,
                   volume_indices, planarity_groups, volume_target=None, scale=None):
    """Run _inflate from one stage-1 starting point, then (if it
    inflated at all) a light final planarity pass at the same pressure.
    Returns (pts, edge_stretch, weight_reached) -- weight_reached is 0.0
    if the very first pressure step was already rejected (see _inflate),
    meaning this start never actually inflated.

    `volume_indices`/`planarity_groups` are the precomputed structures
    _residual needs (see its docstring), forwarded to _inflate and used
    directly in the final polish pass below.
    `volume_target` is forwarded to _inflate (see its docstring).
    `scale`, if given, is the characteristic edge length used for the
    MIN_3D_EXTENT threshold below in place of `edge_length` itself --
    needed when `edge_length` is a per-edge array (a subdivided fabric
    mesh) rather than a single scalar."""
    if scale is None:
        scale = edge_length
    pts, residual, weight = _inflate(pts0, faces, edge_ai, edge_bi, idx, edge_length,
                                      volume_indices, volume_target)
    if weight:
        target = volume_target if volume_target is not None else _sphere_bound_volume(faces, edge_length)
        sol = least_squares(_residual, pts.flatten(),
                             args=(edge_ai, edge_bi, volume_indices, planarity_groups, edge_length,
                                   weight, target, PLANARITY_WEIGHT))
        polished = sol.x.reshape(-1, 3)
        err = _edge_stretch(sol.fun, n_edges)
        if (err < STRETCH_CAP and _overall_3d_extent(polished) > MIN_3D_EXTENT * scale
                and _is_orientation_consistent(polished, faces, idx)):
            pts, residual = polished, err
    return pts, residual, weight


def solve_wireframe(faces, edge_length=EDGE_LENGTH, seed=0, n_restarts=CANDIDATES_PER_ROUND,
                     volume_target=None):
    """Find 3D positions for every vertex that make every mesh edge as
    close to `edge_length` as possible, inflated into a rounded, convex-
    ish shape rather than left as whatever arbitrary (possibly tangled,
    possibly skewed, possibly self-intersecting) configuration a plain
    edge-length fit first finds.

    `edge_length` is normally a scalar (every edge shares one rest
    length, the original behavior). It may instead be a
    {(a, b): length} dict keyed by the same (a, b) pairs mesh_edges(faces)
    produces -- needed for a subdivided fabric mesh, whose fine edges do
    NOT all share one rest length (see mesh_subdivide.py). In that case
    `volume_target` must be given explicitly too, since _sphere_bound_volume's
    regular-polygon-area estimate has no single edge length to work from
    (mesh_subdivide.solve_fabric_mesh derives it from the un-subdivided
    coarse polyhedron instead).

    Two stages, retried over random stage-1 starts, one at a time, until
    one actually works (see below for why it can take more than one):

    1. Edge-length-only relaxation from a random 3D starting guess (the
       system is underdetermined -- 3 coords x N vertices, minus 6 for
       overall rotation/translation, usually well over the number of
       edges -- so many valid solutions exist).
    2. _inflate (see its docstring) from that starting point, then a
       light final planarity pass (PLANARITY_WEIGHT) at the same
       pressure, kept only if it stays within STRETCH_CAP, genuinely
       spatial (not collapsed flat), and orientation-consistent (see
       _is_orientation_consistent). The overall result of stage 2 is
       accepted as final only if it clears all of that AND has no two
       DISTINCT vertices closer than MIN_SEPARATION_FRACTION *
       edge_length -- orientation-consistency alone doesn't rule out two
       unrelated vertices landing on (almost) the same point, which
       _mesh_volume's pressure term has no particular reason to avoid
       on its own.

    Whether a given stage-1 start ends up producing a genuinely
    inflated, non-self-intersecting result varies, in ways that aren't
    safe to predict from the start alone, which is why this tries them
    one at a time (up to MAX_ORIENTATION_ATTEMPTS total, in batches of
    CANDIDATES_PER_ROUND before pausing to reconsider) and stops at the
    FIRST one that succeeds, rather than picking one stage-1 candidate
    up front by some simpler heuristic and committing to it -- or,
    conversely, exhaustively comparing many successes against each
    other, which repeated testing showed rarely helps (once a mesh
    inflates at all, essentially every successful attempt lands on the
    same result -- see tests/test_stretchy_mesh.py) and was, for a
    slower mesh like the dodecahedron, a lot of wasted computation:

    - Plain edge-length fitting has no opinion at all about orientation,
      so a random stage-1 start is often already self-intersecting --
      one face folded inside-out relative to the rest. That's NOT
      automatically a lost cause, though: for a well-connected mesh like
      the dodecahedron (20 vertices, 30 edges), _inflate's very first,
      gentle pressure step reliably resolves it into a fully consistent,
      well-separated shape regardless -- inflating IS the untangling
      mechanism there, so requiring an already-consistent stage-1 start
      would just throw away perfectly good candidates for no benefit
      (and did, in an earlier version of this function).
    - But for other meshes -- stretchy_nets/two_pentagons_and_a_square.json
      is the sharpest example -- a stage-1 start can be a "fragile"
      orientation-consistent embedding that _inflate's very first
      pressure step immediately flips right back out of, backing off to
      zero inflation for that particular start even though the mesh
      overall clearly CAN inflate (observed empirically: roughly half of
      even the already-consistent starting points get stuck this way,
      while the others reliably reach the same well-inflated result). No
      amount of retrying with the SAME start fixes this -- it needs a
      different one, hence trying several.

    If MAX_ORIENTATION_ATTEMPTS is exhausted with no success at all, it
    raises ValueError rather than silently returning a self-intersecting
    mess -- see the message for what to check.

    Returns (positions, stats): positions is {vertex_id: np.array([x, y,
    z])}, stats has "max_stretch_pct" and "rms_stretch_pct" (how far the
    settled edges ended up from `edge_length`) plus "residual" (the raw
    max |edge-length error|)."""
    vertex_ids = sorted({v for face in faces for v in face})
    idx = {v: i for i, v in enumerate(vertex_ids)}
    edges = mesh_edges(faces)
    if not edges:
        raise ValueError("mesh has no edges")
    n = len(vertex_ids)
    edge_ai, edge_bi = _pair_index_arrays(edges, idx)
    n_edges = len(edges)
    # Built once here rather than re-derived on every _residual call --
    # see _residual's docstring for why that matters.
    volume_indices = _volume_indices(faces, idx)
    planarity_groups = _planarity_groups(faces, idx)

    if isinstance(edge_length, dict):
        if volume_target is None:
            raise ValueError("volume_target must be given explicitly when edge_length is a dict")
        length_arr = np.array([edge_length[e] for e in edges])
        scale = float(np.min(length_arr))
    else:
        length_arr = edge_length
        scale = float(edge_length)

    rng = np.random.default_rng(seed)
    best = None  # (pts, residual)
    attempted = 0
    budget = n_restarts
    while best is None and attempted < MAX_ORIENTATION_ATTEMPTS:
        for _ in range(min(budget, MAX_ORIENTATION_ATTEMPTS - attempted)):
            x0 = rng.normal(scale=scale, size=3 * n)
            sol = least_squares(_residual, x0,
                                 args=(edge_ai, edge_bi, volume_indices, planarity_groups, length_arr))
            pts0 = sol.x.reshape(-1, 3)
            attempted += 1

            pts, residual, weight = _inflate_from(
                pts0, faces, edge_ai, edge_bi, idx, length_arr, n_edges,
                volume_indices, planarity_groups, volume_target=volume_target, scale=scale)
            if (weight and _is_orientation_consistent(pts, faces, idx)
                    and _min_pairwise_separation(pts) > MIN_SEPARATION_FRACTION * scale):
                # the first success is kept as-is, not compared against
                # further candidates: repeated runs land on essentially
                # the same result once one succeeds at all (see
                # docstring), so searching further just costs time for
                # no real gain -- stop immediately.
                best = (pts, residual)
                break
        budget *= 2

    if best is None:
        raise ValueError(
            f"could not find a non-self-intersecting, inflatable embedding in {attempted} "
            f"attempts: every candidate either folded a face inside-out relative to the "
            f"others (see _is_orientation_consistent) or couldn't inflate at all before "
            f"hitting that. This usually means the mesh's faces aren't consistently "
            f"wound -- every face's vertex list should go counterclockwise as seen from "
            f"the outside of the solid, matching how its neighbors reference the same "
            f"shared vertices (see this module's docstring for the convention and "
            f"stretchy_nets/two_pentagons_and_a_square.json for a worked example); "
            f"double-check each face's vertex order.")
    pts, residual = best

    positions = {v: pts[i] for i, v in enumerate(vertex_ids)}

    lengths = np.array([np.linalg.norm(positions[a] - positions[b]) for a, b in edges])
    stretch_pct = 100 * (lengths - length_arr) / length_arr
    stats = dict(residual=residual,
                 max_stretch_pct=float(np.max(np.abs(stretch_pct))),
                 rms_stretch_pct=float(np.sqrt(np.mean(stretch_pct ** 2))))
    return positions, stats


def _edge_setup(faces, edge_length):
    """Shared setup for relax_once: vertex/edge index arrays, the
    precomputed structures _residual needs for its pressure/planarity
    terms (see _volume_indices/_planarity_groups -- built once here
    rather than re-derived on every _residual call), plus a per-edge
    length array (broadcastable from a scalar) and a characteristic
    scalar scale (the array's min, or the scalar itself)."""
    vertex_ids = sorted({v for face in faces for v in face})
    idx = {v: i for i, v in enumerate(vertex_ids)}
    edges = mesh_edges(faces)
    edge_ai, edge_bi = _pair_index_arrays(edges, idx)
    volume_indices = _volume_indices(faces, idx)
    planarity_groups = _planarity_groups(faces, idx)
    if isinstance(edge_length, dict):
        length_arr = np.array([edge_length[e] for e in edges])
        scale = float(np.min(length_arr)) if len(length_arr) else 1.0
    else:
        length_arr = edge_length
        scale = float(edge_length)
    return (vertex_ids, idx, edges, edge_ai, edge_bi, volume_indices, planarity_groups,
            length_arr, scale)


def _positions_and_stretch(pts, vertex_ids, edges, length_arr):
    positions = {v: pts[i] for i, v in enumerate(vertex_ids)}
    lengths = np.array([np.linalg.norm(positions[a] - positions[b]) for a, b in edges])
    stretch_pct = 100 * (lengths - length_arr) / length_arr
    return positions, float(np.max(np.abs(stretch_pct))), float(np.sqrt(np.mean(stretch_pct ** 2)))


# scipy.optimize.least_squares' own default gtol -- passed explicitly
# (rather than relying on scipy's default) so relax_once's caller can
# always know and display the exact tolerance a reported `optimality`
# value is being compared against, without it silently drifting if a
# future scipy version ever changes its default.
CONVERGENCE_GTOL = 1e-8

# Status codes least_squares returns when it stopped because ITS OWN
# tolerance (gtol/ftol/xtol) was satisfied, as opposed to exhausting
# max_nfev (0) or a Stop request cutting it off early.
_CONVERGED_STATUSES = (1, 2, 3, 4)


class RelaxStopped(Exception):
    """Raised internally by relax_once's residual wrapper when the given
    stop_event is set -- never escapes relax_once itself."""


def relax_once(positions, faces, edge_length, pressure=0.0,
                planarity_weight=PLANARITY_WEIGHT, max_nfev=None, stop_event=None,
                gtol=CONVERGENCE_GTOL):
    """Run ONE relaxation pass from `positions` (a {vertex_id: [x, y, z]}
    dict) at a fixed inflation `pressure` -- no automatic weight ramp, no
    random restarts, no orientation-consistency retries (that machinery
    lives in _inflate/solve_wireframe, for the "just find me a good
    answer" use case; this is for the opposite one: the caller picks the
    pressure and how much work to do, and can call this again with the
    result to keep going, watching it evolve step by step).

    Uses _relax_residual, NOT _residual -- there is deliberately no target
    volume here (see _relax_residual's docstring): a human turning a
    pressure dial expects "more pressure -> more inflated", which a
    target-based penalty can't deliver once volume gets close to its
    (fixed) target -- verified empirically to plateau hard well before
    any dramatic shape change. `pressure` here isn't on the same numeric
    scale as _inflate's INFLATION_WEIGHTS ramp (those target a specific
    volume; this doesn't) -- as a reference point, pressure=6.5 reaches
    about 5.5% max stretch on stretchy_nets/cube_res3.json, which is
    roughly what the old target-based formula needed pressure~100-300
    (i.e. its plateau) to reach.

    `max_nfev` caps the number of solver function evaluations -- used as
    a practical, always-available proxy for "how many steps to run"
    (scipy's trust-region solvers don't expose a cleaner "N iterations"
    knob); None runs to scipy's own convergence tolerance instead.

    `stop_event`, if given (a threading.Event), is checked on every
    residual evaluation -- setting it from another thread (e.g. a "Stop"
    button) aborts at the next evaluation and returns whatever position
    was just evaluated, rather than waiting for scipy's own stopping
    criteria or max_nfev.

    Returns (new_positions, nfev, max_stretch_pct, rms_stretch_pct,
    optimality, converged). `optimality` is scipy's first-order
    optimality measure (a gradient-norm-like quantity that should
    approach 0 at a stationary point -- compare against `gtol`); it's
    None if a stop was requested before scipy ever returned a result.
    `converged` is True only if scipy's own tolerance (gtol/ftol/xtol)
    was what stopped it, False if the step cap or a stop request did."""
    vertex_ids, idx, edges, edge_ai, edge_bi, volume_indices, planarity_groups, length_arr, _ = \
        _edge_setup(faces, edge_length)
    x0 = np.array([positions[v] for v in vertex_ids]).flatten()

    last_x = [x0]
    raw_calls = [0]

    def wrapped_residual(x, *args):
        raw_calls[0] += 1
        last_x[0] = x
        if stop_event is not None and stop_event.is_set():
            raise RelaxStopped()
        return _relax_residual(x, *args)

    try:
        sol = least_squares(wrapped_residual, x0,
                             args=(edge_ai, edge_bi, volume_indices, planarity_groups, length_arr,
                                   pressure, planarity_weight),
                             max_nfev=max_nfev, gtol=gtol)
        pts = sol.x.reshape(-1, 3)
        # scipy's own nfev -- NOT wrapped_residual's raw call count, which
        # can run well past max_nfev's nominal value before scipy checks
        # the cap again (e.g. mid Jacobian estimate): using sol.nfev here
        # keeps a "N steps" request corresponding to roughly N reported
        # steps, matching what the caller (and the app's iteration
        # counter) actually asked for.
        reported_nfev = sol.nfev
        optimality = float(sol.optimality)
        converged = sol.status in _CONVERGED_STATUSES
    except RelaxStopped:
        # scipy never returned, so there's no sol.nfev -- the wrapper's
        # own raw call count is the only number available here, but it
        # counts every individual residual evaluation (including
        # numerical-Jacobian perturbations), which can run to the
        # hundreds or thousands for a single reported "step" (see
        # _residual's docstring) -- reporting that raw count directly
        # would make a Stop request look like it consumed far more
        # "steps" than any step-counting caller (e.g.
        # stretchy_polyhedron_init.py's iteration counter) actually
        # means by that word. Capping it at max_nfev (the caller's own
        # declared step budget for this call, when given) keeps a
        # stopped call's reported cost bounded by something the caller
        # chose, instead of an internal implementation detail.
        pts = last_x[0].reshape(-1, 3)
        reported_nfev = min(raw_calls[0], max_nfev) if max_nfev is not None else raw_calls[0]
        optimality = None
        converged = False

    new_positions, max_stretch, rms_stretch = _positions_and_stretch(pts, vertex_ids, edges, length_arr)
    return new_positions, reported_nfev, max_stretch, rms_stretch, optimality, converged
