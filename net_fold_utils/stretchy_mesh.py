"""Loader + solver for STRETCHY meshes: a closed polyhedron-like net whose
faces are combinatorially valid (every edge shared by exactly two faces)
but that cannot necessarily be realized with perfectly RIGID, FLAT faces
-- e.g. two faces glued together along more than one shared edge, which
forces them into the same plane if both stay flat and rigid (three or
more shared, non-collinear points determine a single plane, so any two
flat polygons sharing that many points must lie in it -- there's no
dihedral fold left to make them distinct faces of a solid). The
net_fold_utils.polyhedron_spec / combinatorics.EdgeMap pipeline used by
polygon_fold_app.py and polyhedral_net_app.py can't even represent this:
EdgeMap's face-adjacency graph is a plain networkx.Graph, so two faces
sharing more than one edge collapses to a single graph edge and raises
"duplicate edge in the edge list" (see tests/test_stretchy_mesh.py for a
worked example, and stretchy_polyhedron_init.py for the app that handles
these).

Rather than the rigid pipeline's hinge-tree-plus-fold-angles model (which
assumes every face stays flat), a stretchy mesh is specified directly as
VERTEX loops -- the standard "indexed face set" representation (like an
.obj file): shared vertices ARE the adjacency, so faces sharing multiple
edges need no special-casing, and there's no "flat 2D net" or "fold
angle" concept to derive at all. JSON shape:

    {
      "name": "...",
      "faces": [
        [0, 1, 2, 3, 4],
        [3, 2, 1, 0, 5],
        [0, 4, 3, 5]
      ]
    }

Each face is a CCW loop of vertex ids (ints, 0..N-1, referenced -- not
separately declared; N is inferred as 1 + the largest id used). For a
valid closed 2-manifold, every directed edge (v, w) appearing in some
face's loop must be matched by exactly one other face's loop containing
the reverse directed edge (w, v) -- same orientation convention as the
rest of this project (net_layout.py: a shared edge is traversed in
opposite directions by its two faces).

solve_wireframe() then finds SOME 3D position for every vertex that
keeps every edge close to unit length, without requiring individual
faces to stay flat -- letting edges stretch a little and faces bend is
exactly what makes an otherwise-rigid-impossible net (like
stretchy_nets/two_pentagons_and_a_square.json) realizable at all. It
works equally well on an ordinary closed solid (see
stretchy_nets/{tetrahedron,cube,octahedron,icosahedron,dodecahedron}.json,
generated by tools/generate_stretchy_platonic_nets.py from the very same
coordinates the RIGID nets/*.json specs come from) -- those settle with
~0% stretch and essentially flat faces, since they genuinely can.
"""
import json

import numpy as np
from scipy.optimize import least_squares

EDGE_LENGTH = 1.0


def _face_edges(face):
    """The directed edges (v, w) of one CCW face loop."""
    k = len(face)
    return [(face[i], face[(i + 1) % k]) for i in range(k)]


def load_stretchy_mesh(path):
    """Parse the vertex-loop JSON format above. Returns (faces, name),
    faces a list of vertex-id lists. Raises ValueError if any directed
    edge isn't matched by exactly one reverse-direction partner (i.e. the
    faces don't combinatorially close into a 2-manifold)."""
    with open(path) as f:
        spec = json.load(f)

    faces = spec.get("faces") or []
    if not faces:
        raise ValueError(f"{path}: no faces declared")
    for face in faces:
        if len(face) < 3:
            raise ValueError(f"{path}: a face needs at least 3 vertices, got {face}")

    directed = [e for face in faces for e in _face_edges(face)]
    counts = {}
    for e in directed:
        counts[e] = counts.get(e, 0) + 1
    problems = []
    for (v, w), c in counts.items():
        if c > 1:
            problems.append(f"edge {v}->{w} appears {c} times (need exactly once)")
        if (w, v) not in counts:
            problems.append(f"edge {v}->{w} has no reverse partner {w}->{v} in any face")
    if problems:
        raise ValueError(f"{path}: not a closed, consistently-oriented mesh:\n  " +
                          "\n  ".join(problems))

    name = spec.get("name") or path
    return faces, name


def mesh_edges(faces):
    """The mesh's unique undirected edges, as (a, b) with a < b."""
    edges = {tuple(sorted(e)) for face in faces for e in _face_edges(face)}
    return sorted(edges)


def _non_edge_pairs(vertex_ids, edges):
    """Every pair of DISTINCT vertices with no edge between them -- the
    pairs the repulsion term (see solve_wireframe) keeps apart."""
    edge_set = {tuple(sorted(e)) for e in edges}
    return [(a, b) for i, a in enumerate(vertex_ids) for b in vertex_ids[i + 1:]
            if (a, b) not in edge_set]


def _pair_index_arrays(pairs, idx):
    """A list of (a, b) vertex-id pairs -> two int arrays of their
    positions in the flat point array, for vectorized pairwise-distance
    residuals (np.linalg.norm(pts[a_idx] - pts[b_idx], axis=1)) instead
    of a Python-level loop calling norm() once per pair -- matters here
    since these residuals are evaluated many times per least_squares
    call, and a mesh like the dodecahedron has ~190 vertex pairs."""
    if not pairs:
        return np.zeros(0, dtype=int), np.zeros(0, dtype=int)
    a_idx = np.array([idx[a] for a, b in pairs])
    b_idx = np.array([idx[b] for a, b in pairs])
    return a_idx, b_idx


def _face_planarity_residual(face_pts):
    """Signed distance of each of a face's points from that face's own
    best-fit plane (via SVD -- the plane through the centroid whose
    normal is the least-variance direction). A triangle (3 points) is
    always exactly planar, so it contributes nothing."""
    if len(face_pts) < 4:
        return np.zeros(0)
    centered = face_pts - face_pts.mean(axis=0)
    normal = np.linalg.svd(centered)[2][-1]
    return centered @ normal


# How strongly to prefer each face staying close to flat, relative to
# keeping edges at unit length. Low: bending is what makes an otherwise
# -impossible mesh like the pentagons-and-square example realizable at
# all, so this must never fight the edge-length fit hard enough to
# meaningfully undo it -- it only nudges the refinement pass toward
# gently-bowed faces instead of leaving whatever arbitrary bending the
# earlier stage happened to produce.
PLANARITY_WEIGHT = 0.15

CONVERGE_TOL = 1e-4  # max |edge length error| to call a solve "converged"
MIN_3D_EXTENT = 0.1  # fraction of edge_length; below this, call the whole result "flat"


def _residual(flat, edge_ai, edge_bi, repel_ai, repel_bi, faces, idx, edge_length,
              planarity_weight=0.0):
    """The full objective: edge-length error for every mesh edge, a
    one-sided repulsion penalty (max(0, edge_length - dist), zero once
    satisfied) for every non-adjacent vertex pair closer than one edge
    length apart, and -- only when planarity_weight > 0 -- a per-face
    flatness term. Always returns edge residuals first, so callers can
    slice `result[:len(edge_ai)]` to get just the edge-length error
    without the other terms."""
    pts = flat.reshape(-1, 3)
    edge_res = np.linalg.norm(pts[edge_ai] - pts[edge_bi], axis=1) - edge_length
    repel_dist = np.linalg.norm(pts[repel_ai] - pts[repel_bi], axis=1)
    repel_res = np.maximum(0.0, edge_length - repel_dist)
    parts = [edge_res, repel_res]
    if planarity_weight:
        planarity_res = np.concatenate([
            planarity_weight * _face_planarity_residual(pts[[idx[v] for v in face]])
            for face in faces
        ]) if faces else np.zeros(0)
        parts.append(planarity_res)
    return np.concatenate(parts)


def _min_pairwise_separation(pts):
    d = np.linalg.norm(pts[:, None, :] - pts[None, :, :], axis=-1)
    np.fill_diagonal(d, np.inf)
    return d.min() if len(pts) > 1 else np.inf


def _overall_3d_extent(pts):
    """The point cloud's smallest principal-axis extent (via SVD) -- near
    zero means the whole mesh has landed flat in a single plane."""
    centered = pts - pts.mean(axis=0)
    return np.linalg.svd(centered, compute_uv=False)[-1]


GOOD_SEPARATION = 0.9  # fraction of edge_length; _solve_once results at or above this stop the retry loop in solve_wireframe
MAX_ATTEMPTS = 3  # different top-level seeds solve_wireframe will try looking for one


def _solve_once(faces, edge_length, seed, n_restarts):
    """Run the full 3-stage relaxation once for one top-level seed.
    Returns (positions, stats, min_separation) -- see solve_wireframe for
    what stats contains and why min_separation is reported separately
    (it's what solve_wireframe's retry loop judges attempts by, but
    isn't itself part of the public per-edge stretch report).

    Three stages, each seeded from the previous one's result so the
    (comparatively expensive) later terms only ever run as a LOCAL
    refinement rather than their own random-restart search:

    1. Edge-length-only relaxation from several random 3D starting
       guesses (the system is underdetermined -- 3 coords x N vertices,
       minus 6 for overall rotation/translation, usually well over the
       number of edges -- so many solutions exist, and this is the cheap
       part, so it's the one that gets to try many of them). Among the
       restarts that converge (residual < CONVERGE_TOL), the one with
       the largest minimum distance between any two DISTINCT vertices is
       kept as a starting point for stage 2.
    2. A repulsion pass: a one-sided penalty, zero once satisfied,
       pushing apart any two non-adjacent vertices closer than
       `edge_length`. Edge-length fitting alone has no opinion at all
       about where non-adjacent vertices end up, and a bigger mesh (e.g.
       the dodecahedron's 20 vertices / 30 edges -- ~54 free parameters
       after removing rigid-body motion, against only 30 constraints)
       can easily settle into a technically-valid but self-tangled
       embedding, with unrelated vertices landing on top of each other.
       A real convex solid never has that -- no two of its vertices are
       ever closer than its own shortest edge (verified for the unit-
       edge Platonic solids in tests/test_stretchy_mesh.py) -- so
       `edge_length` is the same threshold fold_solver._is_embeddable
       uses to reject a collapsed RIGID solution, just enforced here as
       a soft nudge during the optimization (running it as a random-
       restart search of its own, the way stage 1 works, would be far
       more expensive: many more residual terms, evaluated many more
       times).
    3. A planarity pass: adds a light per-face flatness term
       (PLANARITY_WEIGHT) on top of edges + repulsion, so faces settle
       gently bowed rather than dramatically twisted. This MUST run as a
       local refinement, not a random-restart search: for a mesh like
       stretchy_nets/two_pentagons_and_a_square.json, where flat faces
       are only possible if the *whole* mesh goes flat (see this
       module's docstring), "edges near-exact AND faces near-flat" is
       satisfied there too, perfectly -- degenerately. Started fresh
       from a random guess, that flat solution is a strong, easy-to-find
       attractor; started from stage 2's already-spread-out point cloud,
       the optimizer instead only has room to locally smooth each face a
       little before the other terms (which stage 2 already satisfied)
       start pushing back. Kept only if it's still genuinely spatial and
       still converged; otherwise stage 2's result is used as-is."""
    vertex_ids = sorted({v for face in faces for v in face})
    idx = {v: i for i, v in enumerate(vertex_ids)}
    edges = mesh_edges(faces)
    if not edges:
        raise ValueError("mesh has no edges")
    n = len(vertex_ids)
    edge_ai, edge_bi = _pair_index_arrays(edges, idx)
    repel_ai, repel_bi = _pair_index_arrays(_non_edge_pairs(vertex_ids, edges), idx)
    n_edges = len(edges)

    def edge_err(residual):
        return np.max(np.abs(residual[:n_edges])) if n_edges else 0.0

    # -- stage 1: edge lengths only, many random restarts --
    empty = np.zeros(0, dtype=int)
    rng = np.random.default_rng(seed)
    converged, fallback = [], []
    for _ in range(n_restarts):
        x0 = rng.normal(scale=edge_length, size=3 * n)
        sol = least_squares(_residual, x0,
                             args=(edge_ai, edge_bi, empty, empty, faces, idx, edge_length))
        pts = sol.x.reshape(-1, 3)
        err = edge_err(sol.fun)
        fallback.append((err, pts))
        if err < CONVERGE_TOL:
            converged.append((_min_pairwise_separation(pts), err, pts))

    if not converged:
        residual, pts = min(fallback, key=lambda c: c[0])
    else:
        # -- stage 2: local repulsion refinement -- tried on several of
        # stage 1's best (most separated) candidates, not just the top
        # one: repulsion is a one-sided, non-smooth penalty (zero once
        # satisfied), so it can locally push apart pairs that are
        # currently too close but can't "untangle" a badly self-crossed
        # starting point the way a fresh restart with a clean edge-only
        # landscape can -- trying it from a handful of already-decent
        # starting points is cheap insurance against any one of them
        # refining poorly.
        converged.sort(key=lambda c: -c[0])
        candidates = []
        for _, _, start_pts in converged[:5]:
            sol2 = least_squares(_residual, start_pts.flatten(),
                                  args=(edge_ai, edge_bi, repel_ai, repel_bi,
                                        faces, idx, edge_length))
            pts2 = sol2.x.reshape(-1, 3)
            err2 = edge_err(sol2.fun)
            if err2 < CONVERGE_TOL:
                candidates.append((_min_pairwise_separation(pts2), err2, pts2))
        if candidates:
            _, residual, pts = max(candidates, key=lambda c: c[0])
        else:
            _, residual, pts = converged[0]

    # -- stage 3: local planarity refinement --
    sol3 = least_squares(_residual, pts.flatten(),
                          args=(edge_ai, edge_bi, repel_ai, repel_bi, faces, idx, edge_length,
                                PLANARITY_WEIGHT))
    pts3 = sol3.x.reshape(-1, 3)
    err3 = edge_err(sol3.fun)
    if err3 < CONVERGE_TOL and _overall_3d_extent(pts3) > MIN_3D_EXTENT * edge_length:
        pts, residual = pts3, err3

    positions = {v: pts[i] for i, v in enumerate(vertex_ids)}

    lengths = np.array([np.linalg.norm(positions[a] - positions[b]) for a, b in edges])
    stretch_pct = 100 * (lengths - edge_length) / edge_length
    stats = dict(residual=residual,
                 max_stretch_pct=float(np.max(np.abs(stretch_pct))),
                 rms_stretch_pct=float(np.sqrt(np.mean(stretch_pct ** 2))))
    return positions, stats, _min_pairwise_separation(pts)


def solve_wireframe(faces, edge_length=EDGE_LENGTH, seed=0, n_restarts=20):
    """Find 3D positions for every vertex that make every mesh edge as
    close to `edge_length` as possible (a least-squares relaxation, like
    a mass-spring system settling with every spring at its rest length),
    without requiring individual faces to stay flat. See _solve_once for
    the 3-stage relaxation this runs.

    Even with _solve_once's repulsion stage, a single top-level `seed`
    doesn't reliably untangle a bigger mesh (repulsion can push apart
    pairs that end up too close, but it's a local, non-topological-
    changing nudge -- it can't always undo real self-crossing baked in
    by a bad stage-1 starting guess): empirically, only about 2 of every
    5 seeds land the dodecahedron's 20 vertices / 30 edges at its true
    minimum vertex separation (1 edge length -- verified in
    tests/test_stretchy_mesh.py) rather than some visibly tangled
    embedding. So solve_wireframe retries with a few different top-level
    seeds (derived from the one given, so it's still deterministic),
    keeping the best-separated result and stopping early once one
    reaches GOOD_SEPARATION -- the smaller/simpler nets typically settle
    well on the very first attempt, so this rarely costs more than one
    _solve_once call in practice.

    This retrying doesn't help every mesh, though: the icosahedron (12
    vertices, 30 edges -- every vertex adjacent to 5 of the other 11)
    consistently tops out around 0.5 * edge_length no matter the seed or
    how many restarts, both with and without the repulsion stage (it
    actively makes edge-length convergence noticeably worse there rather
    than better, unlike for the dodecahedron). That's a real ceiling of
    this method -- generic-random-start local optimization -- not a bug
    to chase further here: the icosahedron's true regular embedding is
    one narrow, highly symmetric optimum among a much larger set of
    other local optima this landscape offers, for a graph too small and
    densely connected for repulsion to have much room to push things
    apart in. The edges still converge essentially exactly (this is a
    genuinely closed, realizable solid) and the result is still
    non-degenerate and genuinely 3D -- it's just visibly more tangled
    than the dodecahedron's result tends to be. See
    tests/test_stretchy_mesh.py for the actual per-solid numbers.

    Returns (positions, stats): positions is {vertex_id: np.array([x, y,
    z])}, stats has "max_stretch_pct" and "rms_stretch_pct" (how far the
    settled edges ended up from `edge_length`) plus "residual" (the raw
    max |edge-length error|)."""
    best = None
    for attempt in range(MAX_ATTEMPTS):
        positions, stats, min_sep = _solve_once(faces, edge_length, seed + attempt, n_restarts)
        if best is None or min_sep > best[0]:
            best = (min_sep, positions, stats)
        if min_sep >= GOOD_SEPARATION * edge_length:
            break
    _, positions, stats = best
    return positions, stats
